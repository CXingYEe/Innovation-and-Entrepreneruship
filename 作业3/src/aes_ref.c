static const uint8_t RCON[11] = {
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10,
    0x20, 0x40, 0x80, 0x1b, 0x36
};

/*
 * 在GF(2^8)中乘以x，即乘以02
 */
static uint8_t xtime(uint8_t x)
{
    return (uint8_t)((x << 1) ^ ((x >> 7) * 0x1b));
}

/*
 * GF(2^8)通用乘法，仅在逆MixColumns中使用
 */
static uint8_t gf_mul(uint8_t a, uint8_t b)
{
    uint8_t result = 0;

    while (b != 0) {
        if ((b & 1u) != 0) {
            result ^= a;
        }

        a = xtime(a);
        b >>= 1;
    }

    return result;
}

/*
 * AES-128密钥扩展：
 * 16字节主密钥扩展成11个轮密钥，共176字节
 */
static void aes128_key_expand(
    const uint8_t key[16],
    uint8_t round_keys[AES128_ROUND_KEYS_SIZE])
{
    uint32_t bytes = 16;
    uint8_t rcon_index = 1;
    uint8_t temp[4];

    memcpy(round_keys, key, 16);

    while (bytes < AES128_ROUND_KEYS_SIZE) {
        for (int i = 0; i < 4; ++i) {
            temp[i] = round_keys[bytes - 4u + (uint32_t)i];
        }

        if ((bytes % 16u) == 0u) {
            uint8_t first = temp[0];

            temp[0] = SBOX[temp[1]];
            temp[1] = SBOX[temp[2]];
            temp[2] = SBOX[temp[3]];
            temp[3] = SBOX[first];

            temp[0] ^= RCON[rcon_index++];
        }

        for (int i = 0; i < 4; ++i) {
            round_keys[bytes] =
                (uint8_t)(round_keys[bytes - 16u] ^ temp[i]);
            ++bytes;
        }
    }
}

static void add_round_key(
    uint8_t state[16],
    const uint8_t round_keys[AES128_ROUND_KEYS_SIZE],
    int round)
{
    for (int i = 0; i < 16; ++i) {
        state[i] ^= round_keys[round * 16 + i];
    }
}

static void sub_bytes(uint8_t state[16])
{
    for (int i = 0; i < 16; ++i) {
        state[i] = SBOX[state[i]];
    }
}

static void inv_sub_bytes(uint8_t state[16])
{
    for (int i = 0; i < 16; ++i) {
        state[i] = INV_SBOX[state[i]];
    }
}

/*
 * AES状态按列存储：
 *
 * state[0]  state[4]  state[8]  state[12]
 * state[1]  state[5]  state[9]  state[13]
 * state[2]  state[6]  state[10] state[14]
 * state[3]  state[7]  state[11] state[15]
 */
static void shift_rows(uint8_t state[16])
{
    uint8_t temp;

    /* 第1行左移1字节 */
    temp = state[1];
    state[1] = state[5];
    state[5] = state[9];
    state[9] = state[13];
    state[13] = temp;

    /* 第2行左移2字节 */
    temp = state[2];
    state[2] = state[10];
    state[10] = temp;

    temp = state[6];
    state[6] = state[14];
    state[14] = temp;

    /* 第3行左移3字节 */
    temp = state[3];
    state[3] = state[15];
    state[15] = state[11];
    state[11] = state[7];
    state[7] = temp;
}

static void inv_shift_rows(uint8_t state[16])
{
    uint8_t temp;

    /* 第1行右移1字节 */
    temp = state[13];
    state[13] = state[9];
    state[9] = state[5];
    state[5] = state[1];
    state[1] = temp;

    /* 第2行右移2字节 */
    temp = state[2];
    state[2] = state[10];
    state[10] = temp;

    temp = state[6];
    state[6] = state[14];
    state[14] = temp;

    /* 第3行右移3字节，即左移1字节 */
    temp = state[3];
    state[3] = state[7];
    state[7] = state[11];
    state[11] = state[15];
    state[15] = temp;
}

static void mix_columns(uint8_t state[16])
{
    for (int column = 0; column < 4; ++column) {
        uint8_t *a = &state[column * 4];
        uint8_t all =
            (uint8_t)(a[0] ^ a[1] ^ a[2] ^ a[3]);
        uint8_t old_a0 = a[0];

        a[0] ^= all ^ xtime((uint8_t)(a[0] ^ a[1]));
        a[1] ^= all ^ xtime((uint8_t)(a[1] ^ a[2]));
        a[2] ^= all ^ xtime((uint8_t)(a[2] ^ a[3]));
        a[3] ^= all ^ xtime((uint8_t)(a[3] ^ old_a0));
    }
}

static void inv_mix_columns(uint8_t state[16])
{
    for (int column = 0; column < 4; ++column) {
        uint8_t *a = &state[column * 4];

        uint8_t a0 = a[0];
        uint8_t a1 = a[1];
        uint8_t a2 = a[2];
        uint8_t a3 = a[3];

        a[0] =
            gf_mul(a0, 0x0e) ^
            gf_mul(a1, 0x0b) ^
            gf_mul(a2, 0x0d) ^
            gf_mul(a3, 0x09);

        a[1] =
            gf_mul(a0, 0x09) ^
            gf_mul(a1, 0x0e) ^
            gf_mul(a2, 0x0b) ^
            gf_mul(a3, 0x0d);

        a[2] =
            gf_mul(a0, 0x0d) ^
            gf_mul(a1, 0x09) ^
            gf_mul(a2, 0x0e) ^
            gf_mul(a3, 0x0b);

        a[3] =
            gf_mul(a0, 0x0b) ^
            gf_mul(a1, 0x0d) ^
            gf_mul(a2, 0x09) ^
            gf_mul(a3, 0x0e);
    }
}

static void aes128_encrypt_ref(
    const uint8_t input[16],
    uint8_t output[16],
    const uint8_t round_keys[AES128_ROUND_KEYS_SIZE])
{
    uint8_t state[16];

    memcpy(state, input, 16);

    add_round_key(state, round_keys, 0);

    for (int round = 1; round < 10; ++round) {
        sub_bytes(state);
        shift_rows(state);
        mix_columns(state);
        add_round_key(state, round_keys, round);
    }

    /* 最后一轮没有MixColumns */
    sub_bytes(state);
    shift_rows(state);
    add_round_key(state, round_keys, 10);

    memcpy(output, state, 16);
}

static void aes128_decrypt_ref(
    const uint8_t input[16],
    uint8_t output[16],
    const uint8_t round_keys[AES128_ROUND_KEYS_SIZE])
{
    uint8_t state[16];

    memcpy(state, input, 16);

    add_round_key(state, round_keys, 10);

    for (int round = 9; round > 0; --round) {
        inv_shift_rows(state);
        inv_sub_bytes(state);
        add_round_key(state, round_keys, round);
        inv_mix_columns(state);
    }

    inv_shift_rows(state);
    inv_sub_bytes(state);
    add_round_key(state, round_keys, 0);

    memcpy(output, state, 16);
}

static void print_hex(
    const char *label,
    const uint8_t *data,
    size_t length)
{
    printf("%-21s", label);

    for (size_t i = 0; i < length; ++i) {
        printf("%02X", data[i]);
    }

    putchar('\n');
}

