int main(void)
{
    /*
     * AES-128标准已知答案测试：
     *
     * Key:
     * 000102030405060708090A0B0C0D0E0F
     *
     * Plaintext:
     * 00112233445566778899AABBCCDDEEFF
     *
     * Ciphertext:
     * 69C4E0D86A7B0430D8CDB78070B4C55A
     */
    const uint8_t key[16] = {
        0x00,0x01,0x02,0x03,
        0x04,0x05,0x06,0x07,
        0x08,0x09,0x0a,0x0b,
        0x0c,0x0d,0x0e,0x0f
    };

    const uint8_t plaintext[16] = {
        0x00,0x11,0x22,0x33,
        0x44,0x55,0x66,0x77,
        0x88,0x99,0xaa,0xbb,
        0xcc,0xdd,0xee,0xff
    };

    const uint8_t expected_ciphertext[16] = {
        0x69,0xc4,0xe0,0xd8,
        0x6a,0x7b,0x04,0x30,
        0xd8,0xcd,0xb7,0x80,
        0x70,0xb4,0xc5,0x5a
    };

    uint8_t round_keys[AES128_ROUND_KEYS_SIZE];
    uint8_t ciphertext[16];
    uint8_t recovered_plaintext[16];

    aes128_key_expand(key, round_keys);

    aes128_encrypt_ref(
        plaintext,
        ciphertext,
        round_keys);

    aes128_decrypt_ref(
        ciphertext,
        recovered_plaintext,
        round_keys);

    int encryption_ok =
        memcmp(
            ciphertext,
            expected_ciphertext,
            AES_BLOCK_SIZE) == 0;

    int decryption_ok =
        memcmp(
            recovered_plaintext,
            plaintext,
            AES_BLOCK_SIZE) == 0;

    printf(
        "===== AES-128 REFERENCE IMPLEMENTATION TEST =====\n");

    print_hex("Key:", key, 16);
    print_hex("Plaintext:", plaintext, 16);
    print_hex(
        "Expected ciphertext:",
        expected_ciphertext,
        16);
    print_hex(
        "Actual ciphertext:",
        ciphertext,
        16);
    print_hex(
        "Recovered plaintext:",
        recovered_plaintext,
        16);

    printf(
        "\nEncryption KAT: %s\n",
        encryption_ok ? "PASS" : "FAIL");

    printf(
        "Decryption KAT: %s\n",
        decryption_ok ? "PASS" : "FAIL");

    printf(
        "Overall result: %s\n",
        encryption_ok && decryption_ok
            ? "ALL TESTS PASSED"
            : "TEST FAILED");

    return encryption_ok && decryption_ok ? 0 : 1;
}
#endif /* AES_NO_MAIN */
